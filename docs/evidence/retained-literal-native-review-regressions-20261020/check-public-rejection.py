#!/usr/bin/env python3
"""One genuine rejected family member through the frozen public evaluate API.

The generated bytes must match the retained relocation packet's C30654 input
identity and counts. No component result is supplied or patched in this run.
"""
import argparse
from datetime import datetime, timezone
import json
from pathlib import Path
import platform
import runpy
import tempfile
import time

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
E = REPO / 'docs/evidence'


def program():
    # Exact fixture constructor from relocation-refinement/check.py:program.
    return (b'with Silver_IO;\nprocedure Main is\n pragma SPARK_Mode (On);\nbegin\n'
            + b'\n'.join([b'Silver_IO.Put ("a");'] * 30654)
            + b'\nend Main;\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    api = runpy.run_path(str(E / 'retained-literal-native-completion-20261019/compose.py'))
    runpy.run_path(str(E / 'retained-literal-pipeline-20261018/compose.py'))['arguments'](parser)
    parser.add_argument('--gas-root', type=Path, required=True)
    parser.add_argument('--cxx-include', type=Path)
    parser.add_argument('--scratch-root', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    timer = time.perf_counter()
    started = datetime.now(timezone.utc).isoformat()
    raw = program()
    boundary = api['read'](E / 'retained-literal-relocation-refinement-20261018/result.json')[
        'adjacent_unit_literal_call_boundary']['30654']
    assert api['identity'](raw) == boundary['source_identity']
    assert boundary['counts'] == dict(calls=30654, nulls=0, decoded_bytes=30654, maximum_literal_length=1)
    context = api['Context'](args.gcc_root, args.ada_root, args.plugin_include,
                            args.gas_root, args.gcc_match, args.cxx_include)
    args.scratch_root.mkdir(exist_ok=True, parents=True)
    with tempfile.TemporaryDirectory(prefix='public-rejection-', dir=args.scratch_root) as scratch:
        source = Path(scratch) / 'main.adb'
        source.write_bytes(raw)
        result = api['evaluate'](E / 'retained-literal-pipeline-20261018/selected-route.json', context, source)
        # Keep the complete return value before checking our summary adapter.
        # This scratch artifact permits diagnosis without repeating evaluation.
        retained = args.scratch_root / 'public-return.json'
        retained.write_text(json.dumps(result, indent=2)+'\n')
    assert result['source'] == boundary['source_identity']
    assert result['source_counts']['output_calls'] == 30654
    assert result['source_counts']['null_statements'] == 0
    assert result['source_counts']['decoded_literal_bytes'] == 30654
    assert result['complete_native_capacity'] is False and result['native_residuals']
    assert result['components'] == {} and all(v is None for v in result['coverage'].values())
    linker = result['register_result']['predecessor_result']['core_result']['literal_output_linker']
    assert linker['source_identity'] == boundary['source_identity']
    assert linker['link']['failed_sufficient_checks'] == boundary['failed_sufficient_checks']
    summary = dict(status='passed', target_commit='a3af18004743d36328a499760699305357389fb8',
        input_kind='fresh genuine family member; no supplied or mutated component result',
        model=dict(selected='GPT-6.1 Sol', effort='Extra High', runtime_confirmation=False),
        source=result['source'], source_counts=result['source_counts'], complete_native_capacity=False,
        component_joins_executed=False, coverage=result['coverage'],
        native_residuals=result['native_residuals'], refined_linker_failed_checks=linker['link']['failed_sufficient_checks'],
        retained_boundary_source_and_counts_matched=True, aggregate_acceptance_boundary_established=False,
        repository_inputs_checked=len(context.manifest['repository']),
        compiler_shell_sources_checked=context.shell_sources_checked,
        corpus_roots={k: str(getattr(args, k)) for k in ('gcc_root', 'ada_root', 'plugin_include', 'gas_root')},
        host=platform.platform(), native_tool_executions=0, broad_suite_replayed=False,
        started_UTC=started, finished_UTC=datetime.now(timezone.utc).isoformat(),
        elapsed_seconds=time.perf_counter()-timer)
    args.output.write_text(json.dumps(summary, indent=2)+'\n')
    print(json.dumps({k: summary[k] for k in ('status', 'source', 'complete_native_capacity', 'refined_linker_failed_checks', 'elapsed_seconds')}))


if __name__ == '__main__':
    main()
